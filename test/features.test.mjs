import test from 'node:test';
import assert from 'node:assert/strict';
import { Chats, CHAT_TTL, INVITE_TTL } from '../lib/chats.mjs';
import {DatabaseSync} from 'node:sqlite';

test('group invites, member scope, replies, typing and receipts', () => {
  let now = 0;
  const codes = ['ABC234', 'DEF567', 'GHI789'];
  const chats = new Chats(() => now, () => codes.shift());
  const id = chats.createGroup('a');
  const invite = chats.groupInvite('a', id);
  assert.deepEqual(chats.requestConnection('b',invite.code,'User.Name'),{pending:true});
  assert.deepEqual(chats.snapshot('b'),[]);
  const request=chats.connectionRequests('a')[0].id;
  assert.throws(()=>chats.respondConnection('c',request,true),{status:404});
  assert.equal(chats.respondConnection('a',request,true).id,id);
  assert.equal(chats.snapshot('a')[0].messages[0].text,'User.Name has joined the group.');
  chats.connect('c',invite.code);
  chats.respondConnection('a',chats.connectionRequests('a')[0].id,true);
  assert.equal(chats.snapshot('b')[0].memberCount, 3);
  assert.throws(() => chats.groupInvite('b', id));
  assert.throws(() => chats.send('x', id, 'not allowed'));
  const message = chats.send('a', id, 'hello');
  assert.equal(chats.snapshot('a')[0].messages.find(m=>m.id===message).status, 'sent');
  chats.acknowledge('b', [{ id, delivered: [message], read: [] }]);
  chats.acknowledge('c', [{ id, delivered: [message], read: [] }]);
  assert.equal(chats.snapshot('a')[0].messages.find(m=>m.id===message).status, 'delivered');
  chats.acknowledge('b', [{ id, read: [message] }]);
  chats.acknowledge('c', [{ id, read: [message] }]);
  assert.equal(chats.snapshot('a')[0].messages.find(m=>m.id===message).status, 'read');
  chats.setTyping('b', id, true);
  assert.deepEqual(chats.snapshot('a')[0].typing, ['User.Name']);
  now = 4501;
  assert.deepEqual(chats.snapshot('a')[0].typing, []);
  chats.send('b', id, 'reply', message);
  assert.equal(chats.snapshot('c')[0].messages.at(-1).reply.text, 'hello');
  assert.throws(() => chats.send('b', id, 'bad', 'unknown'));
  now = INVITE_TTL;
  assert.throws(() => chats.connect('x', invite.code));
  now = CHAT_TTL;
  assert.equal(chats.snapshot('a').length, 0);
});

test('group member can leave without removing other members', () => {
  const chats = new Chats();
  const id = chats.createGroup('a');
  chats.connect('b', chats.groupInvite('a', id).code);
  chats.respondConnection('a',chats.connectionRequests('a')[0].id,true);
  chats.remove('b', id);
  assert.equal(chats.snapshot('b').length, 0);
  assert.equal(chats.snapshot('a').length, 1);
});

test('group descriptions and closed invites survive restart while submitted requests remain reviewable', t => {
  const db = new DatabaseSync(':memory:');
  t.after(() => db.close());
  const codes = ['ABC234','DEF567'];
  let chats = new Chats(() => 1000, () => codes.shift());
  chats.attachSupportStore(db);
  const id = chats.createGroup('owner','Workshop','  Bring a piece to share.  ');
  assert.deepEqual(chats.groupInvite('owner',id,'status'),{closed:false});
  const invite = chats.groupInvite('owner',id,'open');
  assert.deepEqual(chats.previewGroupInvite('visitor',id),{groupName:'Workshop',groupDescription:'Bring a piece to share.'});
  assert.deepEqual(chats.connectionRequests('owner'),[]);
  chats.requestConnection('visitor',invite.code,'Visitor');
  assert.throws(() => chats.editGroupDescription('owner',id,'x'.repeat(161)),{status:400});
  chats.editGroupDescription('owner',id,'Monthly workshop');
  assert.deepEqual(chats.groupInvite('owner',id,'close'),{closed:true});
  assert.throws(() => chats.requestConnection('late',invite.code),{status:404});
  assert.equal(chats.respondConnection('owner',chats.connectionRequests('owner')[0].id,true).id,id);
  assert.throws(() => chats.groupInvite('visitor',id,'open'),{status:403});
  assert.throws(() => chats.editGroupDescription('visitor',id,'Changed'),{status:403});
  chats = new Chats(() => 1000, () => codes.shift());
  chats.attachSupportStore(db);
  assert.equal(chats.snapshot('visitor')[0].groupDescription,'Monthly workshop');
  assert.deepEqual(chats.groupInvite('owner',id,'status'),{closed:true});
  assert.throws(() => chats.groupInvite('owner',id),{status:409});
  assert.notEqual(chats.groupInvite('owner',id,'open').code,invite.code);
});

test('group and message timers work independently across restarts and staff joining is visible',()=>{
  const db=new DatabaseSync(':memory:');
  try{
    let now=1;
    let chats=new Chats(()=>now);
    chats.attachSupportStore(db);
    const id=chats.createGroup('owner','Workshop');
    assert.throws(()=>chats.groupTimers('outside',id,{groupTimer:'never',chatTimer:'1h'}),{status:404});
    chats.groupTimers('owner',id,{groupTimer:'never',chatTimer:'1h'});
    chats.joinGroup('staff',id,null,true);
    chats.joinGroup('staff',id,null,true);
    assert.equal(chats.snapshot('owner')[0].messages.length,1);
    assert.match(chats.snapshot('owner')[0].messages[0].text,/qzu\. Staff has joined/);
    chats.send('staff',id,'Hello from staff');
    chats=new Chats(()=>now);
    chats.attachSupportStore(db);
    assert.deepEqual(chats.groups('staff').map(row=>[row.name,row.joined,row.persistent]),[['Workshop',true,true]]);
    assert.equal(chats.snapshot('staff')[0].messages.at(-1).text,'Hello from staff');
    now+=3600000;
    assert.equal(chats.snapshot('owner')[0].messages.length,0);
    chats.groupTimers('owner',id,{groupTimer:'1h',chatTimer:'never'});
    chats.send('owner',id,'Last message');
    now+=3600000;
    assert.equal(chats.groups('staff').length,0);
    assert.equal(db.prepare('SELECT count(*) AS n FROM group_rooms').get().n,0);
  }finally{db.close();}
});

test('group posting settings restrict members and preserve verified roles after restart', t => {
  const db = new DatabaseSync(':memory:');
  t.after(() => db.close());
  const role = id => ({staff:'admin',owner:'verified-seller'}[id]);
  let chats = new Chats();
  chats.groupRole = role;
  chats.activeSeller = id => id === 'owner';
  chats.attachSupportStore(db);
  const id = chats.createGroup('owner','Workshop');
  chats.joinGroup('staff',id,null,true);
  chats.joinGroup('member',id,'Member');
  const earlier = chats.send('member',id,'Earlier message');
  assert.throws(() => chats.updateGroupSettings('member',id,{posting:'owner',description:''}),{status:403});
  const ordinary = chats.createGroup('member');
  assert.throws(() => chats.updateGroupSettings('member',ordinary,{posting:'everyone',description:'',shopLinked:true}),{status:403});
  chats.updateGroupSettings('owner',id,{posting:'admins',description:'',shopLinked:true});
  assert.throws(() => chats.send('member',id,'Blocked'),{status:403});
  assert.throws(() => chats.send('member',id,'',null,{kind:'image'}),{status:403});
  assert.throws(() => chats.edit('member',id,earlier,'Blocked edit'),{status:403});
  chats.setTyping('member',id,true);
  const ownerMessage = chats.send('owner',id,'Shop update');
  const staffMessage = chats.send('staff',id,'Moderator here');
  let group = chats.snapshot('member').find(room=>room.id===id);
  assert.equal(group.canWrite,false);
  assert.equal(group.groupShop,true);
  assert.deepEqual(group.typing,[]);
  assert.equal(group.messages.find(message=>message.id===ownerMessage).senderRole,'verified-seller');
  assert.equal(group.messages.find(message=>message.id===staffMessage).senderRole,'admin');
  assert.equal(group.messages.find(message=>message.system&&message.senderRole)?.senderRole,'admin');
  chats.updateGroupSettings('owner',id,{posting:'owner',description:'',shopLinked:false});
  assert.throws(() => chats.send('staff',id,'Blocked staff'),{status:403});
  chats = new Chats();
  chats.groupRole = role;
  chats.activeSeller = id => id === 'owner';
  chats.attachSupportStore(db);
  group = chats.snapshot('member').find(room=>room.id===id);
  assert.equal(group.groupPosting,'owner');
  assert.equal(group.groupShop,false);
  chats.updateGroupSettings('owner',id,{posting:'everyone',description:''});
  assert.ok(chats.send('member',id,'Members can send again'));
});
