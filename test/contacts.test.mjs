import test from 'node:test';
import assert from 'node:assert/strict';
import { openAccounts, createAccount, findAccount } from '../lib/accounts.mjs';
import { initDevices, findDeviceAccount } from '../lib/devices.mjs';
import { Chats, CHAT_TTL } from '../lib/chats.mjs';
import { contactStore, CONTACT_WARNING, CONTACT_GRACE, retireAccount } from '../lib/contacts.mjs';

test('contacts survive room expiry and restart, aliases are private, activity extends retention',()=>{
  let time=1000000;
  const db=openAccounts(':memory:');
  const store=contactStore(db,()=>time);
  const chats=new Chats(()=>time);
  chats.contacts=store;
  const code=chats.newCode('b').code;
  chats.requestConnection('a',code,'My B');
  const req=chats.connectionRequests('b')[0];
  assert.equal(JSON.stringify(req).includes('My B'),false);
  const first=chats.respondConnection('b',req.id,true,'My A').id;
  const id=store.list('a')[0].id;
  assert.equal(store.list('a')[0].nickname,'My B');
  assert.equal(store.list('b')[0].nickname,'My A');
  assert.equal(chats.snapshot('a')[0].contact.nickname,'My B');
  assert.equal(JSON.stringify(chats.snapshot('b')).includes('My B'),false);
  assert.throws(()=>chats.openContact('c',id));
  time+=CHAT_TTL+1;
  assert.equal(chats.snapshot('a').length,0);
  const restarted=new Chats(()=>time);
  restarted.contacts=contactStore(db,()=>time);
  const second=restarted.openContact('a',id);
  assert.notEqual(first,second);
  assert.equal(restarted.snapshot('a')[0].messages.length,0);
  time=1000000+CONTACT_WARNING;
  assert.equal(store.list('a')[0].warning,true);
  const fresh=restarted.openContact('b',id);
  restarted.send('a',fresh,'hello');
  assert.equal(store.list('b')[0].warning,false);
  time+=CONTACT_WARNING+CONTACT_GRACE;
  assert.equal(store.list('a').length,0);
  assert.throws(()=>restarted.openContact('a',id));
  db.close();
});
test('permanent logout detaches device, invalidates old account token and removes contacts',()=>{
  const db=openAccounts(':memory:');initDevices(db);
  const a=createAccount(db,'device-a'), b=createAccount(db,'device-b');
  const store=contactStore(db);
  store.add(a.id,b.id,'B','A');
  retireAccount(db,store,a.id);
  assert.equal(findDeviceAccount(db,'device-a'),null);
  assert.equal(findAccount(db,a.token),null);
  assert.equal(store.list(b.id).length,0);
  assert.notEqual(createAccount(db,'device-a').id,a.id);
  db.close();
});
